#!/usr/bin/env node
// Ask Zero State · builds workers/ask/knowledge.md from the official pages in site-manifest.json.
// The assistant may only answer from this file, so it never says more than the site says.
// `node scripts/ask-knowledge.js` writes it; `verify()` reports when it is stale.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = 'workers/ask/knowledge.md';
const SITE = 'https://zer0state.com/';
// Pages that add nothing a visitor would ask about, or only repeat other pages.
const SKIP = new Set(['marketing.html', 'media/hexwire.html']);

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', middot: '·', rarr: '→', larr: '←', mdash: '—', ndash: '–', hellip: '…' };
const decode = (s) => s
  .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
  .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
  .replace(/&([a-z]+);/gi, (m, n) => ENTITIES[n.toLowerCase()] ?? m);

function pageUrl(file) {
  if (file === 'index.html') return SITE;
  return SITE + file;
}

// Page HTML → plain text with headings, list items and absolute links kept.
function toText(html, file) {
  const base = new URL(pageUrl(file));
  let main = (html.match(/<main[\s\S]*?<\/main>/i) || [html])[0];
  main = main
    .replace(/<(script|style|svg|template|figure|picture)[\s\S]*?<\/\1>/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<a\b[^>]*href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/gi, (_, href, label) => {
      const text = label.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
      if (!text || href.startsWith('#')) return text;
      let url;
      try { url = new URL(decode(href), base).href; } catch { return text; }
      return url === text ? url : `${text} (${url})`;
    })
    .replace(/<h([1-6])\b[^>]*>/gi, (_, n) => `\n${'#'.repeat(Math.min(Number(n) + 1, 6))} `)
    .replace(/<\/h[1-6]>/gi, '\n')
    .replace(/<li\b[^>]*>/gi, '\n- ')
    .replace(/<\/(span|small|em|strong|b|time)>/gi, ' ')
    .replace(/<(br|\/p|\/div|\/section|\/ul|\/ol|\/dl|\/dd|\/dt|\/tr)\b[^>]*>/gi, '\n')
    .replace(/<[^>]+>/g, ' ');
  return decode(main)
    .split('\n')
    .map((line) => line.replace(/[ \t ]+/g, ' ').trim())
    .filter((line, i, all) => line && !(line.startsWith('#') && all[i + 1] === undefined))
    .join('\n')
    .replace(/\n(#+ )/g, '\n\n$1');
}

function render(root = ROOT) {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'site-manifest.json'), 'utf8'));
  const files = (manifest.pages || [])
    .map((p) => (p.endsWith('.html') ? p : `${p}.html`))
    .filter((f) => !SKIP.has(f));
  const sections = files.map((file) => {
    const html = fs.readFileSync(path.join(root, file), 'utf8');
    const title = decode((html.match(/<title>([\s\S]*?)<\/title>/i) || [, file])[1]).trim();
    return `## ${title}\nURL: ${pageUrl(file)}\n\n${toText(html, file)}`;
  });
  return [
    '# Zero State website content',
    `Generated by scripts/ask-knowledge.js from site-manifest.json (site ${manifest.version}). Do not edit by hand.`,
    ...sections,
  ].join('\n\n') + '\n';
}

const PUBLIC_EMAIL = 'zer0state@zer0state.com';
const SECRET_LIKE = /\b(sk-[A-Za-z0-9_-]{16,}|gh[pousr]_[A-Za-z0-9]{20,}|AKIA[0-9A-Z]{16}|xox[abpr]-[A-Za-z0-9-]{10,})\b|-----BEGIN [A-Z ]*PRIVATE KEY-----/;

// Every project card on the home page must have a section, and nothing private may slip in.
function verify(root = ROOT) {
  const file = path.join(root, OUT);
  if (!fs.existsSync(file)) return [`${OUT}: missing; run node scripts/ask-knowledge.js`];
  const text = fs.readFileSync(file, 'utf8');
  const problems = text === render(root) ? [] : [`${OUT}: stale; run node scripts/ask-knowledge.js`];
  const home = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  const projects = new Set([...home.matchAll(/href="((?:products|clients|community|skills)\/[a-z0-9-]+\.html)"/g)].map((m) => m[1]));
  for (const page of projects) {
    if (!text.includes(`URL: ${SITE}${page}`)) problems.push(`${OUT}: project ${page} is on the home page but not in the knowledge file`);
  }
  for (const email of new Set(text.match(/[\w.%+-]+@[\w-]+(?:\.[\w-]+)+/g) || [])) {
    if (email.toLowerCase() !== PUBLIC_EMAIL) problems.push(`${OUT}: contains email ${email}; only ${PUBLIC_EMAIL} may appear`);
  }
  if (SECRET_LIKE.test(text)) problems.push(`${OUT}: contains a credential-like string`);
  return problems;
}

if (require.main === module) {
  const text = render();
  fs.mkdirSync(path.dirname(path.join(ROOT, OUT)), { recursive: true });
  fs.writeFileSync(path.join(ROOT, OUT), text);
  console.log(`${OUT}: ${text.length} chars, ~${Math.round(text.length / 4)} tokens`);
}

module.exports = { render, verify, toText, OUT };
